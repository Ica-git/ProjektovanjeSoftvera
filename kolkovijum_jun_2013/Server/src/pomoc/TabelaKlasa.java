public class TabelaKlasa {
    
    private int brojKolone;
    private int brojVrednost;

    public TabelaKlasa() {
    }

    public TabelaKlasa(int brojKolone, int brojVrednost) {
        this.brojKolone = brojKolone;
        this.brojVrednost = brojVrednost;
    }

    public int getBrojVrednost() {
        return brojVrednost;
    }

    public void setBrojVrednost(int brojVrednost) {
        this.brojVrednost = brojVrednost;
    }

    public int getBrojKolone() {
        return brojKolone;
    }

    public void setBrojKolone(int brojKolone) {
        this.brojKolone = brojKolone;
    }
    
    
    
    
}
