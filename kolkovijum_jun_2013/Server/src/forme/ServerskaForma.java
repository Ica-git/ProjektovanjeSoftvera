    public void izvrsiUpit() {

        SwingUtilities.invokeLater(() -> {
            ArrayList<TabelaKlasa> noviRed = new ArrayList<>();
            for (int i = 0; i < ModelTabeleServer.BROJ_KOLONA; i++) {
                int vrednost = (int) (Math.random() * 30) + 1; // 1..30
                noviRed.add(new TabelaKlasa(i, vrednost));
            }
            ModelTabeleServer mt = (ModelTabeleServer) tblServer.getModel();
            mt.postaviRed(noviRed);
        });

    }

