    private void serverPokrenutUI() {
        SimpleDateFormat sdf = new SimpleDateFormat("HH:mm");
        lblPokernut.setText("Server pokrenut  " + sdf.format(new Date()));
        jScrollPane1.setVisible(true);
        lblSat.setVisible(true);
        NitSat ns = new NitSat(lblSat);
        ns.start();
        btnPokreniServer.setVisible(false);
    }
    
    private void portZauzetUI() {
        lblPokernut.setText("Port 9000 je zauzet");
    }

    private void srediTabelu() {
        ModelTabeleServer mts = new ModelTabeleServer();
        tblServer.setModel(mts);
    }

    public String odradiPosaoKojiTreba(int pozicija, String korisnickoIme) {
        
        if (pozicija < 1 || pozicija > ModelTabeleServer.BROJ_KOLONA) {
            return "Pozicija mora biti izmedju 1 i " + ModelTabeleServer.BROJ_KOLONA;
        }
        final int kolona = pozicija - 1;
        javax.swing.SwingUtilities.invokeLater(() -> {
            ModelTabeleServer mt = (ModelTabeleServer) tblServer.getModel();
            mt.postaviVrednostUKoloni(kolona, 100);
        });
        return "Korisnik " + korisnickoIme + " je izbacio igraca sa pozicije " + pozicija;

    }
    
    
