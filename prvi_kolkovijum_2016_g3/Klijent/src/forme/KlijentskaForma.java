    private void btnSacuvajUcinakActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSacuvajUcinakActionPerformed
        // TODO add your handling code here:
        ModelTabeleKlijent mtk = (ModelTabeleKlijent) tblUcinakRadnika.getModel();
        SimpleDateFormat sdf = new SimpleDateFormat("dd.MM.yyyy");
        
        ArrayList<Ucinak> lista = mtk.getLista();
        
        for (int i = 0; i < lista.size(); i++) {
            Ucinak u1 = lista.get(i);
            for (int j = i + 1; j < lista.size(); j++) {
                Ucinak u2 = lista.get(j);
                
                if (u1.getRadnik().getRadnikID() == u2.getRadnik().getRadnikID()
                        && u1.getVrstaPosla().getVrstaPoslaID() != u2.getVrstaPosla().getVrstaPoslaID()) {
                    JOptionPane.showMessageDialog(this, "Radnik moze raditi samo jednu vrstu posla!");
                    return;
                }
            }
        }
        
        for (int i = 0; i < lista.size(); i++) {
            Ucinak u1 = lista.get(i);
            int ukupnoSati = u1.getBrojSati();
            String dat1 = sdf.format(u1.getDatum());
            for (int j = i + 1; j < lista.size(); j++) {
                Ucinak u2 = lista.get(j);
                String dat2 = sdf.format(u2.getDatum());
                
                if (u1.getRadnik().getRadnikID() == u2.getRadnik().getRadnikID()
                        && dat1.equals(dat2)) {
                    
                    ukupnoSati += u2.getBrojSati();
                    
                }
            }
            
            if (ukupnoSati > 8) {
                JOptionPane.showMessageDialog(this, "Radnik moze raditi max 8 sati!");
                return;
            }
        }
        
        if (lista.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Popunite ucinke!");
            return;
        }
        
        try {
            KlijentskiZahtev kz = new KlijentskiZahtev(Operacije.SACUVAJ_UCINAK, lista);
            Komunikacija.getInstance().posaljiZahtev(kz);
            ServerskiOdgovor so = Komunikacija.getInstance().primiOdgovor();

            if (so != null && so.getOdgovor() != null && (Boolean) so.getOdgovor()) {
                JOptionPane.showMessageDialog(this, "Uspesno sacuvano!");
            }else{
                JOptionPane.showMessageDialog(this, "Nije uspesno!");
                return;
        }
        } catch (Exception ex) {
            Logger.getLogger(KlijentskaForma.class.getName()).log(Level.SEVERE, null, ex);
            JOptionPane.showMessageDialog(this, "Greška: " + ex.getMessage());
        }
        
        
        
    }//GEN-LAST:event_btnSacuvajUcinakActionPerformed

    private void btnDodajUcinakActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDodajUcinakActionPerformed
        // TODO add your handling code here:
        
        SimpleDateFormat sdf = new SimpleDateFormat("dd.MM.yyyy");
        
        VrstaPosla vp = (VrstaPosla) cmbVrstaPosla.getSelectedItem();
        Radnik r = (Radnik) cmbRadnik.getSelectedItem();
        
        String br = txtBrojSati.getText();
        String dat = txtDatum.getText();
        
        if (br.isEmpty() || dat.isEmpty()) {
            JOptionPane.showMessageDialog(this,"Sva polja moraju biti popunjena!");
            return;
        }
        
        for (int i = 0; i < br.length(); i++) {
            if (!Character.isDigit(br.charAt(i))) {
                JOptionPane.showMessageDialog(this,"Broj mora biti cifra!");
                return;
            }
        }
        
        Date datum = null;
        
        int brojSati = Integer.parseInt(br);
        
        try {
            datum = sdf.parse(dat);
        } catch (ParseException ex) {
                JOptionPane.showMessageDialog(this,"Datum nije u dobrom formatu!");
                return;
        }
        
        Ucinak u = new Ucinak(-1, brojSati, datum, r, vp);
        
        ModelTabeleKlijent mtk = (ModelTabeleKlijent) tblUcinakRadnika.getModel();
        
        mtk.dodajUcinak(u);
        
        
    }//GEN-LAST:event_btnDodajUcinakActionPerformed

