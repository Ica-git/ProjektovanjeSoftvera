    private void popuniComboVrstePoslova() {
        
        KlijentskiZahtev kz = new KlijentskiZahtev(Operacije.VRATI_SVE_VRSTE_POSLOVA, null);
        Komunikacija.getInstance().posaljiZahtev(kz);
        ServerskiOdgovor so = Komunikacija.getInstance().primiOdgovor();
        
        if (so != null && so.getOdgovor() != null) {
            
            ArrayList<VrstaPosla> lista = (ArrayList<VrstaPosla>) so.getOdgovor();
            cmbVrstaPosla.removeAllItems();
            
            for (VrstaPosla vp : lista) {
                cmbVrstaPosla.addItem(vp);
            }
            
        }
        
    }

    private void popuniComboRadnika() {
        
        KlijentskiZahtev kz = new KlijentskiZahtev(Operacije.VRATI_SVE_RADNIKE, null);
        Komunikacija.getInstance().posaljiZahtev(kz);
        ServerskiOdgovor so = Komunikacija.getInstance().primiOdgovor();
        
        if (so != null && so.getOdgovor() != null) {
            ArrayList<Radnik> lista = (ArrayList<Radnik>) so.getOdgovor();
            cmbRadnik.removeAllItems();
            
            for (Radnik r : lista) {
                cmbRadnik.addItem(r);
            }
        }
        
    }

